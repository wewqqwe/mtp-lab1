"""Частотный анализ слов.

Модуль получает готовый текст и возвращает частоты слов. Он ничего
не знает о файлах и о выводе на экран, поэтому его удобно проверять
на строках прямо в интерпретаторе.
"""

import re
from collections import Counter

#: слово — последовательность букв и дефисов между ними
WORD_PATTERN = re.compile(r"[а-яёa-z]+(?:-[а-яёa-z]+)*", re.IGNORECASE)

#: служебные слова, которые не несут смысла в частотном списке
STOP_WORDS = frozenset([
    "и", "в", "во", "не", "на", "с", "со", "а", "то", "все", "она",
    "так", "его", "но", "да", "ты", "к", "у", "же", "вы", "за", "бы",
    "по", "только", "ее", "мне", "было", "вот", "от", "меня", "еще",
    "нет", "о", "из", "ему", "теперь", "когда", "даже", "ну", "вдруг",
    "ли", "если", "уже", "или", "ни", "быть", "был", "него", "до",
    "вас", "нибудь", "опять", "уж", "вам", "ведь", "там", "потом",
    "себя", "ничего", "ей", "может", "они", "тут", "где", "есть",
    "надо", "ней", "для", "мы", "тебя", "их", "чем", "была", "сам",
    "чтоб", "без", "будто", "чего", "раз", "тоже", "себе", "под",
    "что", "как", "это", "он", "я",
])


def split_words(text):
    """Разбить текст на слова в нижнем регистре.

    :param text: исходный текст
    :return: список слов в порядке появления
    """
    return [match.group(0).lower() for match in WORD_PATTERN.finditer(text)]


def count_words(text, skip_stop_words=True):
    """Посчитать, сколько раз встречается каждое слово.

    :param text: исходный текст
    :param skip_stop_words: пропускать ли служебные слова
    :return: счётчик ``слово -> количество``
    """
    words = split_words(text)
    if skip_stop_words:
        words = [word for word in words if word not in STOP_WORDS]
    return Counter(words)


def most_common(text, limit=5, skip_stop_words=True):
    """Выбрать самые частые слова текста.

    При равной частоте слова идут по алфавиту: иначе порядок зависел бы
    от того, какое слово встретилось в тексте раньше, и результат было бы
    неудобно проверять.

    :param text: исходный текст
    :param limit: сколько слов вернуть
    :param skip_stop_words: пропускать ли служебные слова
    :return: список пар ``(слово, количество)``
    """
    counter = count_words(text, skip_stop_words)
    ordered = sorted(counter.items(), key=lambda pair: (-pair[1], pair[0]))
    return ordered[:limit]


def unique_ratio(text):
    """Посчитать долю уникальных слов в тексте.

    Показатель говорит о разнообразии словаря: чем ближе к единице,
    тем реже слова повторяются.

    :param text: исходный текст
    :return: доля уникальных слов от 0 до 1, либо 0 для пустого текста
    """
    words = split_words(text)
    if not words:
        return 0.0
    return round(len(set(words)) / len(words), 4)
